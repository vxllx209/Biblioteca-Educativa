export type Category =
  | 'Ciencias'
  | 'Matemáticas'
  | 'Historia'
  | 'Literatura'
  | 'Filosofía'
  | 'Ciudadanía'
  | 'Tecnología'
  | 'Otros'

/** School level a book is recommended for (Chilean curriculum). */
export type Level = '4° medio'

export interface CoverStyle {
  bg: string
  fg: string
  accent: string
  pattern: 'lines' | 'dots' | 'arcs' | 'grid' | 'waves'
}

/** Editorial metadata, written by hand in data/books.ts. */
export interface BookInfo {
  id: string
  title: string
  author: string
  category: Category
  subject: string
  description: string
  synopsis: string
  rating: number
  ratingsCount: number
  language: string
  /** Year of first publication (negative = BCE). */
  year: number
  /** Edition the digital text comes from. */
  edition: string
  popularity: number
  premium: boolean
  cover: CoverStyle
  tags: string[]
  /** Recommended for these school levels. */
  levels?: Level[]
  /** Rights note shown on the book page when it differs from plain public domain. */
  rights?: string
  /** Study material written for the app (not a public-domain text). */
  original?: boolean
  /**
   * Reading guide for a work still under copyright: the guide is readable here and the
   * work itself is borrowed legally elsewhere.
   */
  access?: { label: string; url: string; note: string }
}

export interface ChapterMeta {
  title: string
  subtitle?: string
  part?: string
  chars: number
}

export interface AudioTrack {
  title: string
  file: string
  seconds: number
}

/** Facts about the real text and recording, generated by scripts/build-library.ts. */
export interface LibraryMeta {
  words: number
  bytes: number
  /** Where the public-domain text comes from (absent for original material). */
  sourceUrl?: string
  chapters: ChapterMeta[]
  audio?: { archiveId: string; mirrors: string[]; tracks: AudioTrack[] }
}

export interface Book extends BookInfo, LibraryMeta {
  pages: number
  hasAudio: boolean
  sizeMB: number
}

